/**
 * The dev-seed proposals (test/fixtures/agentic/seed-proposals.json) are exactly what the pipeline
 * produces from the stubbed model turns over the recorded pages: the Proposed facts screen and
 * its e2e test show real gate output, not hand-made rows. Regenerate with
 *   UPDATE_AGENTIC_SEED=1 npx vitest run test/agentic/seed.test.ts
 * Person-level (synthetic) conversations are not part of the seed.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { HttpClient } from '../../src/core/http.js';
import { AgenticPipeline, ReplayModel } from '../../src/agentic/index.js';
import { AGENTIC_SEED_FILE } from '../../src/server/serve.js';
import { AGENTIC_FIXTURES, STUBBED } from './paths.js';
import { REQUESTS } from './requests.js';

const NOW = new Date('2026-10-11T12:00:00Z');
export const SEED_REQUESTS = ['babel', 'webpack', 'moment', 'leftpadIncident', 'express', 'osc', 'elastic'] as const;

describe('dev-seed proposals', () => {
  it('match the pipeline output on recorded data', async () => {
    const p = new AgenticPipeline({ model: new ReplayModel(STUBBED), http: new HttpClient({ offline: true, fixturesDir: AGENTIC_FIXTURES, cacheDir: false }), now: NOW, cacheDir: false });
    for (const k of SEED_REQUESTS) await p.request(REQUESTS[k]!);
    const report = p.report();
    const seed = { _note: 'Generated by test/agentic/seed.test.ts: the verification gate run on recorded pages with stubbed model turns.', proposals: report.proposals };
    if (process.env.UPDATE_AGENTIC_SEED === '1') writeFileSync(AGENTIC_SEED_FILE, `${JSON.stringify(seed, null, 2)}\n`);
    expect(JSON.parse(readFileSync(AGENTIC_SEED_FILE, 'utf8'))).toEqual(seed);
    expect(report.proposals.map((x) => x.status).sort()).toEqual(['pending_confirmation', 'pending_confirmation', 'unverified', 'verified', 'verified', 'verified', 'verified', 'verified', 'verified', 'verified']);
    expect(report.privacyRejections).toHaveLength(2);
  });
});
