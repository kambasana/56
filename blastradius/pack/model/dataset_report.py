"""Write the committed dataset manifest and the Markdown dataset report from a build's outputs.

    python pack/model/dataset_report.py --labels out/labels --dataset out/dataset \
        --universe out/universe --sources sources.json --manifest pack/model/manifest \
        --report pack/model/reports/<date>-dataset.md

The manifest is what makes the dataset rebuildable without committing it: the positive labels
(slim), the negative package lists, and every input's URL, commit or SHA-256 (sources.json, written
by hand-run fetch steps; see the report). Numbers in the report are copied from the build outputs.
"""
from __future__ import annotations

import argparse
import collections
import gzip
import json
import os
import shutil


def table(rows: list[list], head: list[str]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def auc(pos: list[float], neg: list[float]) -> float | None:
    """Mann-Whitney AUC with ties counted half; None when a class is empty."""
    if not pos or not neg:
        return None
    allv = sorted([(v, 1) for v in pos] + [(v, 0) for v in neg])
    rank_sum, i = 0.0, 0
    while i < len(allv):
        j = i
        while j < len(allv) and allv[j][0] == allv[i][0]:
            j += 1
        r = (i + j + 1) / 2  # average 1-based rank
        rank_sum += r * sum(1 for k in range(i, j) if allv[k][1] == 1)
        i = j
    return (rank_sum - len(pos) * (len(pos) + 1) / 2) / (len(pos) * len(neg))


def separation(path: str, names: list[str], split: str) -> dict[str, dict]:
    """Per feature, on one split: AUC of the raw value (known values only) and NaN rate per class."""
    vals = {n: ([], []) for n in names}
    nan = {n: [0, 0] for n in names}
    tot = [0, 0]
    with gzip.open(path, "rt") as f:
        for line in f:
            r = json.loads(line)
            if r["split"] != split:
                continue
            y = r["label"]
            tot[y] += 1
            for n, x in zip(names, r["features"]):
                if x is None:
                    nan[n][y] += 1
                else:
                    vals[n][1 - y].append(x)
    out = {}
    for n in names:
        a_ = auc(vals[n][0], vals[n][1])
        out[n] = {"auc": a_, "nanPos": nan[n][1] / max(tot[1], 1), "nanNeg": nan[n][0] / max(tot[0], 1)}
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--labels", required=True)
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--universe", required=True)
    ap.add_argument("--sources", required=True)
    ap.add_argument("--manifest", required=True)
    ap.add_argument("--report", required=True)
    ap.add_argument("--downloads-failures")
    a = ap.parse_args()
    lr = json.load(open(os.path.join(a.labels, "labels_report.json")))
    dr = json.load(open(os.path.join(a.dataset, "report.json")))
    src = json.load(open(a.sources))
    labels = [json.loads(l) for l in open(os.path.join(a.labels, "labels.jsonl")) if l.strip()]

    os.makedirs(a.manifest, exist_ok=True)
    with open(os.path.join(a.manifest, "labels.jsonl"), "w") as f:
        for r in labels:
            f.write(json.dumps({k: r[k] for k in ("name", "version", "publishedAt", "campaign", "manifest", "sources")}, separators=(",", ":")) + "\n")
    for name in ("negatives.txt", "hammer.txt", "controls.txt"):
        if os.path.exists(os.path.join(a.universe, name)):
            shutil.copy(os.path.join(a.universe, name), os.path.join(a.manifest, f"universe-{name}"))
    sources = {**src, "labels": lr["sources"], "criteria": lr["criteria"], "featureSchema": dr["featureSchema"], "sampling": dr.get("sampling"), "timeRange": dr["timeRange"]}
    with open(os.path.join(a.manifest, "sources.json"), "w") as f:
        json.dump(sources, f, indent=1)

    curated = [d for d in lr["dropped"] if any(not s.startswith("osv:") for s in (d["source"] if isinstance(d["source"], list) else [d["source"]]))]
    cov = dr["featureCoverage"]
    manifest_feats = set(dr["manifestFeatures"])
    L = []
    w = L.append
    w(f"<!-- Generated by pack/model/dataset_report.py from the build outputs; numbers are copied, not edited. -->\n")
    w(f"# Training dataset: {dr['rows']['positive']} compromised releases, {dr['rows']['negative']} negatives\n")
    w(f"Feature schema `{dr['featureSchema']}`, rows as of release + {dr['asOfOffsetMs'] // 60000} min, built with the features CLI (`src/features/cli.ts rows --allow-missing-manifest --downloads`), the same code scan time uses. Time range of the rows: {dr['timeRange'][0][:10]} to {dr['timeRange'][1][:10]}.\n")
    w("## Counts\n")
    w(table([
        ["Positive releases (labelled compromised)", dr["rows"]["positive"]],
        ["… without a manifest (npm unpublished them; manifest features NaN)", dr["rows"]["positiveWithoutManifest"]],
        ["Positive packages", lr["positivePackages"]],
        ["Campaigns", lr["campaigns"]],
        ["Negative releases (sampled)", dr["rows"]["negative"]],
        ["… without a manifest (unpublished, no advisory)", dr["rows"]["negativeWithoutManifest"]],
        ["Negative candidates before sampling", dr["sampling"]["negativeCandidates"]],
        ["Negative packages (lists)", dr["packages"]["negative"]],
        ["Acme lockfile packages excluded (gate noise set)", dr["packages"]["controlsExcluded"]],
    ], ["", "n"]))
    w("")
    w("Rows by split hint (time cutoff " + dr["cutoff"][:10] + "; a campaign goes wholly to the side of its first release):\n")
    w(table([[k, v] for k, v in dr["split"].items()], ["split / label / manifest", "rows"]))
    w("")
    w(table([[y, c["pos"], c["neg"]] for y, c in dr["byYear"].items()], ["year", "positives", "negatives"]))
    w("")
    w("## Label sources and licences\n")
    s = lr["sources"]
    w(table([
        ["OSV npm export (MAL-* and GitHub advisories with CWE-506)", s["osv"]["licence"], f"{s['osv']['url']}, downloaded {s['osv']['downloaded']}, sha256 `{s['osv']['sha256'][:16]}…`, {s['osv']['records']} records", lr["bySource"].get("osv", 0)],
        ["tstromberg/supplychain-attack-data", s["sad"]["licence"], f"commit `{(s['sad']['commit'] or '')[:12]}`, {s['sad']['attacks']} npm attacks", lr["bySource"].get("sad", 0)],
        ["Incident KB (kb/incidents)", s["kb"]["licence"], f"{s['kb']['kbIncidents']} incidents", lr["bySource"].get("kb", 0)],
        ["Replay incidents (test/replay)", "this repository", f"{s['kb']['replayIncidents']} incidents", lr["bySource"].get("replay", 0)],
    ], ["source", "licence", "snapshot", "positives citing it"]))
    w("\nA positive can cite several sources. The GitHub advisory database API (`/advisories?cwes=506`) is not reachable from this session (sessions are bound to their repositories); its CWE-506 advisories are taken from the OSV export, which mirrors GitHub-reviewed advisories.\n")
    c = lr["criteria"]
    w("**Positive rule** (labels.py): a version some source calls malicious, of a package that had at least "
      f"{c['minCleanPriorReleases']} release(s) not called malicious and at least {c['minHistoryDays']:.0f} days of history before its first bad release (from the packument `time` map, which npm keeps for unpublished versions). "
      f"Records whose versions of a package span more than {c['maxSpanDays']:.0f} days are affected ranges, not publish-time compromises, and are not used for that package. "
      f"Packages with more than {c['maxLiveStream']} bad versions, most still live on npm, are package-level classifications and are dropped. Whole-package malware (a range covering every version) is never a positive.\n")
    w(f"**Campaigns**: supplychain-attack-data ids, merged into families when their texts name the same campaign marker; KB and replay ids; positives sharing a release are one campaign; named campaigns with positives within {c['namedMergeHours']:.0f} h are merged; an OSV-only positive joins the named campaign with a positive within {c['campaignWindowDays']:.0f} days, otherwise OSV-only positives are chained in time (gap ≤ {c['chainGapDays']:.0f} day, span ≤ {c['chainMaxSpanDays']:.0f} days; named by first date). This errs towards fewer, larger campaigns so a campaign-grouped split cannot put one wave on both sides.\n")
    w("## Positives per campaign\n")
    rows = [[k, v["positives"], v["packages"], v["first"]] for k, v in lr["byCampaign"].items()]
    w(table(rows, ["campaign", "positives", "packages", "first bad release"]))
    w("")
    w("## External features: what is real, what is excluded\n")
    w(table([
        ["downloads_weekly_log10, downloads_trend", "api.npmjs.org/downloads/range (historical daily counts)", "used: the 7 days ending two days before the release day, and the 12 weeks before that", f"pos {cov['downloads_weekly_log10']['pos']:.1%} / neg {cov['downloads_weekly_log10']['neg']:.1%} (weekly); pos {cov['downloads_trend']['pos']:.1%} / neg {cov['downloads_trend']['neg']:.1%} (trend)"],
        ["scorecard_score", "api.securityscorecards.dev, deps.dev", "excluded: only today's score exists, which is hindsight for a past release", "0% (NaN on every row)"],
        ["dependents_log10", "deps.dev", "excluded: only today's dependents count exists", "0% (NaN on every row)"],
        ["typosquat_distance", "needs the popular-name list as of the release", "excluded: no as-of list built", "0% (NaN on every row)"],
    ], ["feature", "source", "decision", "coverage"]))
    w("")
    w("Coverage of every feature (share of rows where it is not NaN):\n")
    w(table([[n + (" (manifest)" if n in manifest_feats else ""), f"{v['pos']:.1%}", f"{v['neg']:.1%}"] for n, v in cov.items()], ["feature", "positives", "negatives"]))
    sep = separation(os.path.join(a.dataset, "dataset.jsonl.gz"), dr["featureNames"], "train")
    w("\nUnivariate separation on the training split (AUC of the raw value over rows where it is known; 0.5 = no signal, far from 0.5 either way = strong; a big gap in NaN rate between classes is itself a signal a model can pick up):\n")
    w(table([[n + (" (manifest)" if n in manifest_feats else ""), "n/a" if v["auc"] is None else f"{v['auc']:.3f}", f"{v['nanPos']:.1%}", f"{v['nanNeg']:.1%}"] for n, v in sep.items()], ["feature", "AUC", "NaN pos", "NaN neg"]))
    w("\n**Leakage warning for training.** Most positives have no manifest because npm unpublished them; negatives almost always have one. The manifest features (marked) are therefore NaN mostly on positives, and a model would learn \"manifest missing → malicious\". Train the history-only variant with every manifest feature masked on all rows (the `manifestFeatures` list in the schema), or train the full variant only on rows with `manifest: true`. **Sampling bias warning.** Negatives come from packages popular enough to sit in large lockfiles, while positives include many small packages (worm waves hit whatever their victims maintained), so weekly downloads and release counts separate the classes partly because of how the negatives were chosen, not because of the attack. The positive packages' own clean releases are in the negatives to counter this; a model should be checked within package (positives against the same packages' clean releases) and with per-year weights, since positives cluster in 2025–2026 while negatives spread over 2016–2026.\n")
    w("## Negatives\n")
    w(f"Every release in the positives' time range of: the dependency walk from the Acme lockfiles ({dr['packages']['negativeLists'].get('negatives.txt', 0)} packages ranked by how many Acme packages use them; deps.dev has no top-N listing API, and today's dependents counts would be hindsight for sampling past releases), the hammer control repos' lockfiles at their pinned commits ({dr['packages']['negativeLists'].get('hammer.txt', 0)} packages: microsoft/TypeScript, apache/superset frontend, mochajs/mocha, microsoft/vscode, npm/cli), and the positive packages' own other releases. "
      f"Removed: every version any source lists as malicious, whole-package malware, and the Acme lockfile packages (the backtest gate's noise set). Sampled to at most {dr['sampling']['maxPerPackageYear']} releases per package and calendar year by a hash of name@version (deterministic). \"No advisory\" means no malicious-code advisory (MAL-*, CWE-506, attack data, KB); releases with ordinary vulnerability advisories stay negatives.\n")
    w("## Dropped items\n")
    w(table([[k, v] for k, v in lr["droppedReasons"].items()], ["label candidates dropped: reason", "versions"]))
    w("")
    w(f"Curated-source candidates (attack data, KB, replay) that were dropped: {len(curated)}.\n")
    by = collections.Counter((d["reason"].split(" (")[0], ",".join(sorted({s.split(':')[1] for s in d["source"] if not s.startswith('osv:')}))) for d in curated)
    w(table([[r, s, n] for (r, s), n in by.most_common()], ["reason", "curated source", "versions"]))
    w("")
    if dr["packages"]["dropped"]:
        w("Negative packages without a packument: " + ", ".join(f"{k} ({v})" for k, v in sorted(dr["packages"]["dropped"].items())) + ".\n")
    if dr["droppedRows"]:
        w("Rows the features CLI could not describe: " + ", ".join(f"{k}: {v}" for k, v in dr["droppedRows"].items()) + ".\n")
    if dr["droppedPositives"]:
        w(f"Positives dropped at feature time: {len(dr['droppedPositives'])}.\n")
    if a.downloads_failures and os.path.exists(a.downloads_failures):
        fails = json.load(open(a.downloads_failures))
        if fails:
            w(f"Download history not obtained for {len(fails)} package-years: " + ", ".join(f"{k}: {v}" for k, v in collections.Counter(fails.values()).most_common()) + " (those rows have NaN download features).\n")
        else:
            w("Download history: every requested package-year was fetched (no failures).\n")
    for d in src.get("notes", []):
        w(f"- {d}")
    w("\n## Rebuild\n")
    w("```\n" + "\n".join(src.get("rebuild", [])) + "\n```\n")
    with open(a.report, "w") as f:
        f.write("\n".join(L) + "\n")
    print(a.report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
